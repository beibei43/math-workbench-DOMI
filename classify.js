/* 有些字在中文题面里太常见，单独出现不算特征，只作为组合条件 */
function clean(text){
  return String(text||'')
    .replace(/[０-９]/g, c=>String.fromCharCode(c.charCodeAt(0)-0xFEE0))
    .replace(/[：]/g,':').replace(/[，、；]/g,' ').replace(/\s+/g,' ')
    .toLowerCase();
}

/* 返回：{tag, confidence, score, hits, alternatives:[{tag,score}], needConfirm} */
function classifyTopic(text){
  var s = clean(text), result = [];
  if(!s.trim()) return {tag:'综合',confidence:'无',score:0,hits:[],alternatives:[],needConfirm:true,empty:true};

  Object.keys(RULES).forEach(function(tag){
    var r=RULES[tag], score=0, hits=[];
    if(s.indexOf(tag)>=0 && tag!=='综合' && tag!=='套卷' && tag!=='复盘与总测'){ score+=6; hits.push(tag); }
    (r.s||[]).forEach(function(w){ if(s.indexOf(w.toLowerCase())>=0){ score+=3; hits.push(w); } });
    (r.w||[]).forEach(function(w){ if(s.indexOf(w.toLowerCase())>=0){ score+=1; hits.push(w); } });
    (r.combo||[]).forEach(function(arr){
      if(arr.every(function(w){ return s.indexOf(w.toLowerCase())>=0; })){ score+=4; hits.push(arr.join('+')); }
    });
    /* re = 题面模式（纯算式、数列、颜色周期这类没有文字特征词的题） */
    (r.re||[]).forEach(function(p){
      p[0].lastIndex=0;
      if(p[0].test(s)){ score+=p[1]; hits.push(p[2]); }
    });
    // 命中词种类多但都很泛时，轻微降权，避免长题面乱判
    if(score>0) result.push({tag:tag,score:score,hits:hits.slice(0,6)});
  });

  result.sort(function(a,b){ return b.score-a.score; });
  var top=result[0];
  if(!top || top.score<2){
    return {tag:'综合',confidence:'无',score:top?top.score:0,hits:[],alternatives:result.slice(0,3),needConfirm:true};
  }
  var level = top.score>=7 ? '较高' : (top.score>=4 ? '中等' : '较低');
  return {
    tag: top.tag,
    confidence: level,
    score: top.score,
    hits: top.hits,
    alternatives: result.filter(function(x){ return x.tag!==top.tag && x.score>=2; }).slice(0,3),
    needConfirm: level!=='较高'
  };
}

root.TOPIC_RULES = RULES;
